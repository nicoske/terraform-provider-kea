// ProtoV6ProviderFactories is used to instantiate a provider during
// acceptance testing. The factory function will be invoked for every Terraform
// CLI command executed to create a provider server to which the CLI can
// reattach.
var ProtoV6ProviderFactories = map[string]func() (tfprotov6.ProviderServer, error){
	"kea": providerserver.NewProtocol6WithError(provider.New("test")()),
}

// PreCheck validates required environment variables before running acceptance tests.
// Assumes the Kea server is configured with testing/kea-dhcp4.conf.
func PreCheck(t *testing.T) {
	t.Helper()

	address := os.Getenv("KEA_DHCP4_ADDRESS")
	if address == "" {
		t.Fatal("KEA_DHCP4_ADDRESS must be set for acceptance tests")
	}
}

// PreCheckTLS skips the test unless KEA_DHCP4_TLS_ADDRESS points to the https
// control socket of testing/kea-dhcp4.conf.
func PreCheckTLS(t *testing.T) {
	t.Helper()

	if os.Getenv("KEA_DHCP4_TLS_ADDRESS") == "" {
		t.Skip("KEA_DHCP4_TLS_ADDRESS must be set for TLS acceptance tests")
	}
}

// PreCheckMemfile skips the test unless KEA_DHCP4_MEMFILE_ADDRESS points to
// the control socket of the server configured with
// testing/kea-dhcp4-memfile.conf, which has no hosts database.
func PreCheckMemfile(t *testing.T) {
	t.Helper()

	PreCheck(t)
	if os.Getenv("KEA_DHCP4_MEMFILE_ADDRESS") == "" {
		t.Skip("KEA_DHCP4_MEMFILE_ADDRESS must be set for acceptance tests without a hosts database")
	}
}

// ProviderConfigMemfile configures the provider for the server of
// PreCheckMemfile.
func ProviderConfigMemfile() string {
	return fmt.Sprintf(`
provider "kea" {
  dhcp4 = {
    address = %q
  }
}
`, os.Getenv("KEA_DHCP4_MEMFILE_ADDRESS"))
}

// TLSFile returns the absolute path of a file generated by testing/gen-certs.sh.
func TLSFile(name string) string {
	_, file, _, _ := runtime.Caller(0)
	return filepath.Join(filepath.Dir(file), "..", "..", "testing", "certs", name)
}

func ProviderConfig() string {
	return `
provider "kea" {}
`
}

