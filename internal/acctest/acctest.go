// PreCheck validates required environment variables before running acceptance tests.
// Assumes the Kea server is configured with testing/kea-dhcp4.conf.
func PreCheck(t *testing.T) {
	t.Helper()

	address := os.Getenv("KEA_DHCP4_ADDRESS")
	if address == "" {
		t.Fatal("KEA_DHCP4_ADDRESS must be set for acceptance tests")
	}
}

// PreCheckTLS skips the test unless KEA_DHCP4_TLS_ADDRESS points to the https
// control socket of testing/kea-dhcp4.conf.
func PreCheckTLS(t *testing.T) {
	t.Helper()

	if os.Getenv("KEA_DHCP4_TLS_ADDRESS") == "" {
		t.Skip("KEA_DHCP4_TLS_ADDRESS must be set for TLS acceptance tests")
	}
}

// PreCheckServers skips the test unless KEA_DHCP4_ADDRESS_2 points to the
// control socket of a second server configured with testing/kea-dhcp4-2.conf.
func PreCheckServers(t *testing.T) {
	t.Helper()

	PreCheck(t)
	if os.Getenv("KEA_DHCP4_ADDRESS_2") == "" {
		t.Skip("KEA_DHCP4_ADDRESS_2 must be set for acceptance tests with several servers")
	}
}

// ProviderConfigServers configures the provider with every address in
// servers and strict_sync set to strict.
func ProviderConfigServers(strict bool, servers ...string) string {
	var entries strings.Builder
	for _, server := range servers {
		fmt.Fprintf(&entries, "      { address = %q },\n", server)
	}
	return fmt.Sprintf(`
provider "kea" {
  dhcp4 = {
    servers = [
%s    ]
    strict_sync = %t
  }
}
`, entries.String(), strict)
}

// TLSFile returns the absolute path of a file generated by testing/gen-certs.sh.
func TLSFile(name string) string {
	_, file, _, _ := runtime.Caller(0)
	return filepath.Join(filepath.Dir(file), "..", "..", "testing", "certs", name)
}

func ProviderConfig() string {
	return `
provider "kea" {}
`
}

